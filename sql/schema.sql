-- Abonnés WhatsApp du DataParl' Daily — opt-in explicite depuis
-- dataparl.fr/daily/wa. Seul le numéro est demandé ; le hash SHA-256 du
-- jeton de désinscription à un clic est stocké, jamais le jeton en clair.
create table if not exists wa_abonnes (
  tel        text primary key,          -- format international sans « + » : 33612345678
  jeton_hash text not null,            -- SHA-256 du jeton de désinscription
  actif      boolean not null default true,
  cree_le    timestamptz not null default now(),
  maj_le     timestamptz not null default now()
);

-- Journal des diffusions, pour l'idempotence du cron : relancer le même
-- jour sur le même canal n'envoie rien.
create table if not exists chaine_sends (
  id            bigint generated by default as identity primary key,
  canal         text not null check (canal in ('telegram', 'whatsapp')),
  jour          date not null,
  n_mouvements  int not null default 0,
  cree_le       timestamptz not null default now(),
  unique (canal, jour)
);

-- Aucune politique publique : ces tables ne sont accessibles que via la clé
-- service_role (GitHub Actions), comme les autres tables d'application.
alter table wa_abonnes enable row level security;
alter table chaine_sends enable row level security;
